# Python Temelleri -1- INT & FLOAT

# Python'da sayılar iki ana türde bulunur: tam sayılar (integers) ve ondalıklı sayılar (floats).
# Tam sayılar, negatif veya pozitif tam sayıları temsil ederken, ondalıklı sayılar kesirli sayıları temsil eder.    
# Python'da tam sayılar ve ondalıklı sayılar üzerinde çeşitli matematiksel işlemler gerçekleştirebilirsiniz.
# Python dilinde "#" sembolü ile başlayan satırlar yorum satırlarıdır ve programın çalışmasını etkilemez.
# genellikle, yazdıgımız kodun ne yaptığını açıklamak için kullanılır.
# Program, # sembolü ile başlayan satırları dikkate almaz ve bu satırlar sadece programcılar için bilgi sağlar.

print("Tam Sayılar (Integers) ve Ondalıklı Sayılar (Floats)")


# Tam Sayılar (Integers)
#--------------------------------------------------------
tam_sayi1 = 10
tam_sayi2 = -5
tam_sayi3 = 0

print("Tam Sayılar:")
print("tam_sayi1:", tam_sayi1)
print("tam_sayi2:", tam_sayi2)
print("tam_sayi3:", tam_sayi3)


# Ondalıklı Sayılar (Floats)
#--------------------------------------------------------
ondalikli_sayi1 = 3.14
ondalikli_sayi2 = -2.5
ondalikli_sayi3 = 0.0

print("\nOndalıklı Sayılar:")
print("ondalikli_sayi1:", ondalikli_sayi1)
print("ondalikli_sayi2:", ondalikli_sayi2)
print("ondalikli_sayi3:", ondalikli_sayi3)


# Veri Tiplerini Kontrol Etme
#--------------------------------------------------------
print("Veri Tipleri:")
print("tam_sayi1 tipi:", type(tam_sayi1))  # <class 'int'>  
print("ondalikli_sayi1 tipi:", type(ondalikli_sayi1))  # <class 'float'>
print("tam_sayi2 tipi:", type(tam_sayi2))  # <class 'int'>  
print("ondalikli_sayi2 tipi:", type(ondalikli_sayi2))  # <class 'float'>
print("tam_sayi3 tipi:", type(tam_sayi3))  # <class 'int'>  
print("ondalikli_sayi3 tipi:", type(ondalikli_sayi3))  # <class 'float'>
